//按提供的图象位数据来初始化图象数据(    需要初始化的图象,      图象数据指针, 指针bit_data相对该图象数据里的偏移字节位置, 图象数据格式, 图象宽, 图象高)
static void GT_InitImageDataFromBitData(GNg::sIMAGE *img, const uint8 *bit_data, unsigned int ofs, GNg::COLOR_FORMAT cfmt, int w, int h) {
    uint8 loc_buf[65536];
    GN::sTBUF_INT tbuf(loc_buf, 65536);
    unsigned int pn = (unsigned int)w * (unsigned int)h * GNg::ImgFmtGetByteNum(cfmt);
    uint8 *data = (uint8 *)tbuf.GetSpace(pn);
    memset(data, 0, pn);
    ofs <<= 3;
    unsigned int bi, _pi, pi;
    for(pi = ofs; pi < pn; ++pi) {
        _pi = pi - ofs;
        bi = _pi >> 3;
        if(bit_data[bi] & (1 << (_pi - (bi << 3)))) data[pi] = 0xff; /*模板代码:把位记载的数据释放为字节的数据*/
    }
    img->CreateEmptyToData(w, h, 1, cfmt);
    img->DataFill(data, cfmt, w, h);
}

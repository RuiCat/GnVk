void GT_cRUN_REC::Show(unsigned int updatatime) {
    GNg::cVIEW2D *view = GNg::ViewCur;
#ifdef GN_DEBUG
    if(GN::Key1[GK_F9]) GN_ShowMemoryUsingState(); //显示堆内存使用状态
#endif
    if(zRuntimeStrNum) { /*---------------------------------- 运行测试时间显示 ---------------------------------------------------------*/
        if(zGWPrintReady) {
            //运行时间信息显示位置构建
            int x, y, bw, bh;
            bw = view->orthoW >> 4;
            bh = view->orthoH >> 4;
            x = view->ortho_left + bw;
            y = view->ortho_bottom - bh - aFont.GetFontRangeY();

            aFont.SetText(zpRunTime, zRuntimeStrNum, x, y, 0, 0);
            aFont.Show(aFontColor);
        }
    }
    if(zFocus) { /*--------------------------------------------- 有信息要显示 ----------------------------------------------------------*/
        int mx = view->mouseMX, my = view->mouseMY;
        int rw = view->orthoW >> 3,
            rh = view->orthoH >> 3;
        int tx = rw + view->ortho_left - (rw >> 3),
            ty = rh + view->ortho_top,
            tw = (rw << 2) + (rw << 1) + (rw >> 2),
            th = (rh << 2) + (rh << 1);

        if(GN::Key1[GK_F8]) zInfoOpenChange = true;

        if(zInfoIsOpen) { //信息筐打开时的处理 ---------------------------------------------------------------------------------
            zNowtime[2] += updatatime;
            zNowtime[2] -= updatatime * zAm_s_e[2];

            if(zInfoOpenChange) {
                zAm_s_e[2] = 2;
                zInfoOpenChange = false;
            } else if(zNowtime[2] > zEndtime[2]) {
                zNowtime[2] = zEndtime[2];
                zAm_s_e[2] = 1;
            }
            if(zNowtime[2] < 0) PrintInfoClear(); //结束了 重置一下

            int pw = GNg::Linear(0, tw, zNowtime[2], zEndtime[2]),
                ph = GNg::Linear(0, th, zNowtime[2], zEndtime[2]),
                ffbh = rh >> 1;

            int fx = tx - (rw >> 1),
                fy = ty - ffbh,
                fw = pw + rw,
                fh = ph + rh;

            GNg::ImageDraw(0, fx, fy, fw, fh, aBackColor); //显示信息筐底

            bool is_mouse_focus = !(mx < fx || mx > fx + fw || my < fy || my > fy + fh);
            if(!is_mouse_focus && GN::Mouse1[GM_LEFT]) zAm_s_e[2] = 2; //在信息筐底外点击鼠左键提示退出信息显示

            if(zZoningNum > th && zAm_s_e[2] == 1) { //信息筐滚动操纵
                int move_rng = 0; //移动量
                if(GN::Key[GK_F6]) move_rng = (int)(updatatime >> 1);
                else if(GN::Key[GK_F7]) move_rng = -((int)(updatatime >> 1));
                else { //!!类似 GNu::cSCROLL_RECT::UpdateRun 的滚屏处理 ---------------------------------
                    if(!GN::Mouse[GM_RIGHT]) zKeyOnDown = false;
                    if(GN::Mouse1[GM_RIGHT] && is_mouse_focus) zKeyOnDown = true;

                    if(zKeyOnDown && GN::MouseM) { //按住鼠标右键拖动
                        move_rng = view->mouseMSY;
                        if(move_rng < -38 || move_rng > 38) move_rng <<= 1;
                        else zUpdownValue += (zUpdownValueTg - zUpdownValue) * 0.8f * GN::TimeRatioL;

                    } else if(is_mouse_focus) {
                        if(GN::Mouse1[GM_TOP]) { move_rng = (fh >> 2); } //鼠标滚轮上滚
                        else if(GN::Mouse1[GM_BOTTOM]) {
                            move_rng = -(fh >> 2);
                        } //鼠标滚轮下滚
                        else { //鼠标移动到筐边沿也可以操纵移动
                            if(my <= fy + ffbh) {
                                GNg::ImageDraw(0, fx, fy, fw, ffbh, aWarningColor, 0, 1); //显示上滚动条
                                move_rng = (int)((float)(fh * 12 / 600) * GN::TimeRatioL);
                            }
                            int fy2 = fy + fh - ffbh;
                            if(!move_rng && my >= fy2) {
                                GNg::ImageDraw(0, fx, fy2, fw, ffbh, aWarningColor, 0, 1); //显示下滚动条
                                move_rng = (int)((float)(fh * 12 / 600) * -GN::TimeRatioL);
                            }
                        }
                    }
                }
                if(move_rng > 0) {
                    if(zUpdownValueTg < 0.0f) {
                        if(zUpdownValueTg + (float)move_rng > 0.0f) zUpdownValueTg = 0.0f;
                        else zUpdownValueTg += (float)move_rng;
                    }
                } else if(move_rng < 0) {
                    if((float)(zZoningNum - th) > (-(zUpdownValueTg + (float)move_rng))) zUpdownValueTg += (float)move_rng;
                    else zUpdownValueTg = -((float)(zZoningNum - th));
                }
                zUpdownValue += (zUpdownValueTg - zUpdownValue) * 0.1f * GN::TimeRatioL;
            }
            if(ztValue[0] != pw || ztValue[1] != ph || ztValue[2] != (int)zUpdownValue) aErrorFont.SetText(zpErrorInfo, (unsigned short)zFocus, tx, ty, pw, ph, 0, (int)zUpdownValue);
            aErrorFont.Show(GNg::LinearColor(aFontColor & 0x00ffffff, aFontColor, zNowtime[2], zEndtime[2])); //显示信息
            ztValue[0] = pw;
            ztValue[1] = ph;
            ztValue[2] = (int)zUpdownValue;

        } else { // 信息筐未打开的处理 -------------------------------------------------------------------------------------
            if(zAm_s_e[1]) zNowtime[1] -= updatatime; //来回播放
            else zNowtime[1] += updatatime;
            if(zNowtime[1] > zEndtime[1]) {
                zAm_s_e[1] = 1;
                zNowtime[1] = zEndtime[1];
            } else if(zNowtime[1] < 0) {
                zAm_s_e[1] = 0;
                zNowtime[1] = 0;
            }
            int wdy = ty + GNg::SLinear(0, -(rh >> 2), zNowtime[1], zEndtime[1], 0.0f, GNg::L_START),
                wdx = tx - (rw >> 1),
                wnw = ((int)view->orthoW >> 3) / 5,
                wnh = ((int)view->orthoH >> 1) / 5;
            DrawWarning(wdx, wdy, 0.15f, aWarningColor); //显示感叹号!
            wdx -= wnw >> 1;
            wdy -= wnh >> 1;
            if(zInfoOpenChange || (GN::Mouse1[GM_LEFT] && mx >= wdx && mx <= wdx + wnw && my >= wdy && my <= wdy + wnh)) {
                zZoningNum = aErrorFont.GetInRectOffsetTotalH(zpErrorInfo, zFocus, tw, th);
                if(zZoningNum < th) zZoningNum = th;
                zInfoOpenChange = false;
                zInfoIsOpen = true;
            }
        }
    } //end if zFocus
    /*--------------------------------------------------------- 显示报警WARNING!动画 -------------------------------------------------------*/
    if(zNowtime[0] <= (zEndtime[0] - (int)updatatime)) {
        zNowtime[0] += updatatime;

        int rw = view->orthoW,
            rh = view->orthoH;
        int tx = (rw >> 1) + view->ortho_left,
            ty = (rh >> 1) + view->ortho_top;
        unsigned int tw_color = GNg::Linear(0xff, 0, zNowtime[0], zEndtime[0]);
        GNg::ImageDraw(0, view->ortho_left, view->ortho_top, rw, rh, ((unsigned int)((float)tw_color * 0.7f) << 24) | (aWarningColor & 0x00ffffff));
        DrawWarning(tx, ty - (int)((float)tw_color * ((float)rh * 0.0005f)), 1.0f, (tw_color << 24) | (aWarningColor & 0x00ffffff)); //显示感叹号!
    }
    if(zTextOutID) { /*--------------------------------- 显示所有文本纪录 -------------------------------------------------------------------*/
        if(zTextOutNum) {
            GNg::sTEXT_SET *txi = zTextOutDatas, *txe = zTextOutDatas + zTextOutID;
            for(; txi < txe; ++txi) {
                aFont.SetText(txi->text, txi->count, txi->x, txi->y, txi->w, txi->h, txi->offsetx, txi->offsety);
                aFont.Show(txi->c, txi->blendmode);
            }
        } else {
            zTextOutNum = zTextOutID;
            GN_DeleteArray(zTextOutDatas);
            zTextOutDatas = new GNg::sTEXT_SET[zTextOutNum];
        }
        zTextOutID = 0;
    }
    /*----------------------------------------------- 处理显示绘制筐纪录 -----------------------------------------------------------------*/
    unsigned short drn = zDrawRects.size();
    if(drn) {
        GNg::sDRAW_AREA *_drd = zDrawRects.data;
        GNg::sDRAW_AREA *dr_end = _drd + drn;
        for(; _drd < dr_end; ++_drd)
            GNg::LineFrame2dDraw(_drd->x, _drd->y, _drd->w, _drd->h, 1, _drd->c, 1);
    }
    zDrawRects.reset();

    /*--------------------------------------------------- 记录帧率 -----------------------------------------------------------------------*/
    zFPS_AddTime += updatatime;
    ++zFPS_AddCount;
    if(zFPS_AddTime > 2000) { //两秒以上刷新一次帧率
        zFPS_Value = (unsigned short)((1000.0f / (float)zFPS_AddTime) * (float)zFPS_AddCount);
        zFPS_AddTime = 0;
        zFPS_AddCount = 0;
    }
}

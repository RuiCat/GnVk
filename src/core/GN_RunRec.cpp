void GT_cRUN_REC::PrintInfoSet(const char *text) {
    if(!text) return;
    unsigned int ti = 0, tn = zMaxInfoStrNum - 4, rn = 0;
    for(; ti < tn; ++ti) {
        zpErrorInfo[ti] = text[ti];
        if(text[ti] == '\n') {
            ++rn;
            if(rn >= 254) { //超过最大显示行数时结束
                zFocus = ti + 1 + 3;
                strcpy(zpErrorInfo + (ti + 1), "...");
                return;
            }
        } else if(!text[ti]) { //自然结束
            zFocus = ti;
            return;
        }
    }
    zFocus = ti + 3;
    strcpy(zpErrorInfo + ti, "..."); //超过最大缓冲时结束
}
